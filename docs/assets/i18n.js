const I18N = {
  "en-US": EN,
  "zh-CN": ZH,
  "zh-TW": ZH_TW,
  "fr-FR": FR,
  "de-DE": DE,
  "it-IT": IT,
  "es-ES": ES,
  "ja-JP": JA,
  "ko-KR": KO
};

const LANGUAGES = [
  ["zh-CN", "简体中文"], ["zh-TW", "繁體中文"], ["en-US", "English"],
  ["fr-FR", "Français"], ["de-DE", "Deutsch"], ["it-IT", "Italiano"],
  ["es-ES", "Español"], ["ja-JP", "日本語"], ["ko-KR", "한국어"]
];

function detectLanguage() {
  const saved = localStorage.getItem("lanprint-lang");
  if (saved && I18N[saved]) return saved;
  const nav = (navigator.language || "en-US").replace("_", "-");
  if (I18N[nav]) return nav;
  const base = nav.split("-")[0];
  const match = Object.keys(I18N).find(k => k.split("-")[0] === base);
  return match || "en-US";
}

function translate(lang) {
  const dict = I18N[lang] || {};
  document.documentElement.lang = lang;
  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.getAttribute("data-i18n");
    const value = dict[key] || EN[key];
    if (value) el.textContent = value;
  });
  document.querySelectorAll("[data-i18n-html]").forEach(el => {
    const key = el.getAttribute("data-i18n-html");
    const value = dict[key] || EN[key];
    if (value) el.innerHTML = value;
  });
  const page = (location.pathname.split("/").pop() || "index.html").toLowerCase();
  const titleKey = page.includes("guide") ? "guide_title" : page.includes("bridge") ? "bridge_title" : "hero_title2";
  document.title = "lanPrint — " + (dict[titleKey] || EN[titleKey]);
  const select = document.getElementById("lang");
  if (select) select.value = lang;
  localStorage.setItem("lanprint-lang", lang);
}

document.addEventListener("DOMContentLoaded", () => {
  const select = document.getElementById("lang");
  if (select) {
    select.innerHTML = "";
    LANGUAGES.forEach(([code, name]) => {
      const option = document.createElement("option");
      option.value = code;
      option.textContent = name;
      select.appendChild(option);
    });
    select.addEventListener("change", () => translate(select.value));
  }
  translate(detectLanguage());
});
